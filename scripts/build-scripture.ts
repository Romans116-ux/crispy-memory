/**
 * Generates src/data/bible/public-domain.ts with exact KJV and WEB text for every
 * verse the topics quote. Run with `npm run build:scripture` after adding a quoted verse.
 * NIV text is maintained by hand in src/data/bible/niv.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

import { topics } from '../src/data/topics';
import { expandReference } from '../src/lib/urls';

const require = createRequire(import.meta.url);
const kjv: Record<string, string> = require('kjv/json/verses-1769.json');

const kjvBookNames: Record<string, string> = { Psalm: 'Psalms' };

interface WebEntry {
  type: string;
  chapterNumber?: number;
  verseNumber?: number;
  value?: string;
}

const webCache = new Map<string, WebEntry[]>();
function webBook(book: string): WebEntry[] {
  const file = (book === 'Psalm' ? 'Psalms' : book).toLowerCase().replace(/\s+/g, '');
  if (!webCache.has(file)) {
    const p = path.join(path.dirname(require.resolve('world-english-bible/package.json')), 'json', `${file}.json`);
    webCache.set(file, JSON.parse(readFileSync(p, 'utf8')));
  }
  return webCache.get(file)!;
}

/** Fixes curly quotes left unbalanced when a quotation starts or ends outside the excerpt. */
function balanceQuotes(s: string): string {
  const opens = (s.match(/“/g) ?? []).length;
  const closes = (s.match(/”/g) ?? []).length;
  if (closes > opens) s = s.replace(/”(?=[^”]*$)/, '');
  if (opens > closes) s = `${s.trim()}”`;
  return s.trim();
}

const clean = (s: string) =>
  s
    .replace(/^#\s*/, '')
    .replace(/[[\]]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

function kjvText(ref: string): string {
  const { book, chapter, verses } = expandReference(ref);
  return verses
    .map((v) => {
      const key = `${kjvBookNames[book] ?? book} ${chapter}:${v}`;
      const text = kjv[key];
      if (!text) throw new Error(`KJV missing ${key}`);
      return clean(text);
    })
    .join(' ');
}

function webText(ref: string): string {
  const { book, chapter, verses } = expandReference(ref);
  const entries = webBook(book);
  return verses
    .map((v) => {
      const parts = entries.filter(
        (e) => e.chapterNumber === chapter && e.verseNumber === v && typeof e.value === 'string',
      );
      if (parts.length === 0) throw new Error(`WEB missing ${ref} (${v})`);
      return clean(parts.map((p) => p.value).join(' '));
    })
    .join(' ');
}

const refs = [...new Set(topics.flatMap((t) => t.verses.filter((v) => v.quote).map((v) => v.ref)))].sort();
const out = { KJV: {} as Record<string, string>, WEB: {} as Record<string, string> };
for (const ref of refs) {
  out.KJV[ref] = balanceQuotes(kjvText(ref));
  out.WEB[ref] = balanceQuotes(webText(ref));
}

const file = `// Generated by scripts/build-scripture.ts. Do not edit by hand.
// King James Version and World English Bible text, both in the public domain.

export const KJV: Record<string, string> = ${JSON.stringify(out.KJV, null, 2)};

export const WEB: Record<string, string> = ${JSON.stringify(out.WEB, null, 2)};
`;
writeFileSync(path.join(__dirname, '../src/data/bible/public-domain.ts'), file);
console.log(`Wrote ${refs.length} references for KJV and WEB.`);
